-- Structronyx Renewables CRM only. Apply to its own Supabase project.
create type public.crm_role as enum ('admin', 'employee');

create table public.employee_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role public.crm_role not null default 'employee',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_structronyx_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.employee_profiles(user_id, full_name, role, active)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name',''), 'employee', true)
  on conflict (user_id) do nothing;
  return new;
end; $$;
create trigger on_structronyx_user_created
after insert on auth.users for each row execute procedure public.handle_new_structronyx_user();

create or replace function public.is_structronyx_active()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.employee_profiles p where p.user_id = (select auth.uid()) and p.active = true);
$$;
create or replace function public.is_structronyx_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.employee_profiles p where p.user_id = (select auth.uid()) and p.active = true and p.role = 'admin');
$$;

create table public.quotations (
  id uuid primary key default gen_random_uuid(),
  quotation_no bigint generated by default as identity (start with 434267),
  customer text not null,
  mobile text not null,
  capacity text not null,
  project_value numeric(14,2) not null check (project_value >= 0),
  site text not null,
  status text not null default 'Draft',
  project_type text not null,
  booking_amount numeric(14,2) not null default 0 check (booking_amount >= 0),
  timeline text not null default '15-20 days',
  validity text not null default '7 Days',
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint quotations_no_unique unique (quotation_no)
);
create index quotations_created_at_idx on public.quotations(created_at desc);
create index quotations_customer_idx on public.quotations using gin (to_tsvector('simple', customer || ' ' || mobile || ' ' || site));

alter table public.employee_profiles enable row level security;
alter table public.quotations enable row level security;

create policy "active Structronyx users can read profiles" on public.employee_profiles
  for select to authenticated using (public.is_structronyx_active() and (user_id = (select auth.uid()) or public.is_structronyx_admin()));
create policy "admins manage Structronyx profiles" on public.employee_profiles
  for all to authenticated using (public.is_structronyx_admin()) with check (public.is_structronyx_admin());
create policy "active employees read shared quotations" on public.quotations
  for select to authenticated using (public.is_structronyx_active());
create policy "active employees create quotations" on public.quotations
  for insert to authenticated with check (public.is_structronyx_active() and created_by = (select auth.uid()));
create policy "active employees update shared quotations" on public.quotations
  for update to authenticated using (public.is_structronyx_active()) with check (public.is_structronyx_active());
create policy "admins delete quotations" on public.quotations
  for delete to authenticated using (public.is_structronyx_admin());

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.quotations to authenticated;
grant select, update on public.employee_profiles to authenticated;
